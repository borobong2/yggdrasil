import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.setDefaultTimeout(8000);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const base = 'http://127.0.0.1:3055';
const chip = title => page.locator('button[data-todo-id]').filter({ hasText: title }).first();
const grid = page.getByLabel('시간표', { exact: true });
await page.goto(`${base}/#/calendar`);
await grid.waitFor();
assert.match(page.url(), /\/calendar\/week\//);
await page.goto(`${base}/#/calendar/week/2026-10-26`);
await chip('겹침 A').waitFor();
assert.equal(await page.locator('[data-day-column]').count(), 7);
assert.equal(await page.locator('[data-day-column]').first().getAttribute('data-day-column'), '2026-10-25');
const block = title => chip(title).locator('..');
assert.equal(await block('겹침 A').evaluate(e => Math.round(parseFloat(e.style.width))), 33);
assert.equal(await block('독립 전체 폭').evaluate(e => e.style.width), '100%');
assert.equal(await block('실제 마감 시점').getAttribute('data-calendar-block'), 'point');
assert.equal(await block('실제 마감 시점').evaluate(e => parseFloat(e.style.height)), 24, 'deadline ignores 180-minute estimate');
assert.equal(await block('자정 예정').evaluate(e => parseFloat(e.style.top)), 0);
assert.equal(await block('자정 경계').evaluate(e => parseFloat(e.style.height)), 12);
await page.getByRole('button', { name: '10월 26일 (월) 종일 9개 전체' }).click();
assert.equal(await page.locator('#allday-more-2026-10-26 button[data-todo-id]').count(), 9);
await page.keyboard.press('Escape');
assert.ok(await page.locator('[data-ghost]').count());
await grid.evaluate(e => e.scrollTop = 8 * 48);
const header = await page.locator('.calendar-time-head').boundingBox();
const bounds = await grid.boundingBox();
assert.ok(Math.abs(header.y - bounds.y) < 2, 'header fixed in scroll surface');
mkdirSync('docs/evidence/yg55', { recursive: true });
await page.screenshot({ path: 'docs/evidence/yg55/desktop.png' });
await page.setViewportSize({ width: 1280, height: 800 });
assert.ok(await grid.evaluate(e => e.clientHeight > 280));
await page.setViewportSize({ width: 390, height: 844 });
assert.ok(await grid.evaluate(e => e.scrollWidth > e.clientWidth));
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'only calendar scrolls horizontally');
await grid.evaluate(e => { e.scrollLeft = 136; e.scrollTop = 8 * 48; });
await page.screenshot({ path: 'docs/evidence/yg55/mobile.png' });
await page.locator('.calendar-time-head').getByRole('button', { name: '10월 26일 (월) 하루 보기' }).click();
await page.waitForURL('**/day/2026-10-26');
await grid.waitFor();
// Creation remains keyboard accessible at a time slot.
await page.locator('[data-slot="2026-10-26T11"]').click();
const dialog = page.getByRole('dialog', { name: '할 일 추가' });
await dialog.getByLabel('제목').fill('YG55 생성 검증');
await dialog.getByRole('button', { name: '추가', exact: true }).click();
await chip('YG55 생성 검증').waitFor();
await page.setViewportSize({width:1440,height:900});
await page.goto(`${base}/#/calendar/month/2026-10-26`);
await chip('종일 0').waitFor();
const todos = await (await fetch(`${base}/api/issues`)).json();
const before = todos.find(t => t.title === '종일 0');
await chip('종일 0').focus();
await page.keyboard.press('Space');
await page.waitForTimeout(100);
await page.keyboard.press('ArrowRight');
await page.waitForTimeout(100);
let saved = page.waitForResponse(r => r.url().includes(`/api/todos/${before.id}`) && r.request().method() === 'PATCH');
await page.keyboard.press('Space');
assert.equal((await saved).status(), 200);
let after = (await (await fetch(`${base}/api/issues`)).json()).find(t => t.id === before.id);
assert.notEqual(after.scheduledAt, before.scheduledAt);
assert.equal(after.dueAt, before.dueAt);
saved = page.waitForResponse(r => r.url().includes(`/api/todos/${before.id}`) && r.request().method() === 'PATCH');
await page.getByRole('button', { name: '되돌리기', exact: true }).click();
await saved;
after = (await (await fetch(`${base}/api/issues`)).json()).find(t => t.id === before.id);
assert.equal(after.scheduledAt, before.scheduledAt);
assert.equal(after.scheduledAllDay, before.scheduledAllDay);
for (const mode of ['month', 'week', '3day', 'day', 'list']) {
  await page.goto(`${base}/#/calendar/${mode}/2026-10-26`);
  await page.locator(mode === 'month' ? '[data-day]' : mode === 'list' ? '[data-agenda-day]' : '[data-day-column]').first().waitFor();
  assert.equal(await page.getByRole('group', { name: '보기', exact: true }).getByRole('button').count(), 5);
  assert.match(page.url(), new RegExp(`/calendar/${mode}/`));
}
assert.deepEqual(errors, []);
console.log('PASS YG55: week default/explicit views, Sun–Sat, overlap groups, deadline vs plan, midnight/all-day/ghosts, sticky header, 1440/1280/390, horizontal navigation, creation');
await browser.close();
